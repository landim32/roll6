using System.Text.Json;
using System.Text.Json.Serialization;

namespace Roll6.DTO.Realtime.Console;

/// <summary>
/// A tool the server offers the Claude in one run (094, <c>run.tools[]</c>): the console exposes it on a local MCP
/// server for the run and forwards every call as <c>ToolCall</c>. Generic — the console never knows what it does.
/// </summary>
public class ToolInfo
{
    [JsonPropertyName("name")]
    public string Name { get; set; } = string.Empty;

    [JsonPropertyName("description")]
    public string Description { get; set; } = string.Empty;

    /// <summary>JSON Schema of the arguments (an object schema).</summary>
    [JsonPropertyName("inputSchema")]
    public JsonElement InputSchema { get; set; }
}

/// <summary>A call of a run's tool by the Claude (hub method <c>ToolCall</c>, console → server).</summary>
public class ToolCallInfo
{
    /// <summary>Generated by the console, unique within the run.</summary>
    [JsonPropertyName("callId")]
    public string CallId { get; set; } = string.Empty;

    [JsonPropertyName("name")]
    public string Name { get; set; } = string.Empty;

    /// <summary>The arguments as the Claude sent them (an object, or undefined when none).</summary>
    [JsonPropertyName("arguments")]
    public JsonElement Arguments { get; set; }
}

/// <summary>An image of a tool result: base64, no <c>data:</c> prefix.</summary>
public class ToolImageInfo
{
    [JsonPropertyName("mediaType")]
    public string MediaType { get; set; } = "image/png";

    [JsonPropertyName("data")]
    public string Data { get; set; } = string.Empty;
}

/// <summary>The answer to a <see cref="ToolCallInfo"/> (client method <c>toolResult</c>, server → console).</summary>
public class ToolResultInfo
{
    [JsonPropertyName("callId")]
    public string CallId { get; set; } = string.Empty;

    [JsonPropertyName("isError")]
    public bool IsError { get; set; }

    [JsonPropertyName("text")]
    public string Text { get; set; } = string.Empty;

    [JsonPropertyName("images")]
    public List<ToolImageInfo> Images { get; set; } = new();

    public static ToolResultInfo Error(string callId, string text) => new() { CallId = callId, IsError = true, Text = text };
}
